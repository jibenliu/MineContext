const MESSAGES: Record<Locale, Messages> = { 'zh-CN': zh, 'en-US': en }

/**
 * 取词条：缺 key 时回退中文；中文也没有就返回 key 本身（可见而不是空白）。
 * 带 `params` 时把词条里的 `{name}` 换成实参 —— 缺的占位符原样留下（可见而不是消失）。
 */
export function translate(locale: Locale, key: string, params?: MessageParams): string {
  const template = MESSAGES[locale]?.[key] ?? zh[key] ?? key
  if (!params) return template
  const values: MessageParams = params
  return template.replace(/\{(\w+)\}/g, (placeholder, name: string) =>
    name in values ? String(values[name]) : placeholder
  )
}

export interface I18n {
  locale: Locale
  t(key: string, params?: MessageParams): string
}

/** 组件外取当前语言（模块级常量、工具函数里用；组件内请用 `useI18n`）。 */
export function getLocale(): Locale {
  return ((store.getState().setting as { locale?: Locale }).locale ?? DEFAULT_LOCALE) as Locale
}

/** 组件里用它取词条（语言变化会触发重渲染）。 */
export function useI18n(): I18n {
  // 直接订阅 store 单例，而不是 `useSelector`：后者需要一个 redux `<Provider>`，
  // 组件级测试不包 Provider 就取不到词条。语言变化同样会触发重渲染。
  const locale = useSyncExternalStore(
    (onStoreChange) => store.subscribe(onStoreChange),
    () => ((store.getState().setting as { locale?: Locale }).locale ?? DEFAULT_LOCALE) as Locale
  )
  const t = useCallback((key: string, params?: MessageParams) => translate(locale, key, params), [locale])
  return { locale, t }
}
