#!/usr/bin/env bash
# 安全与隐私属性的**测试门禁**：规划里承诺的那 11 条，必须真的各有测试。
#
# 为什么需要它：承诺写在文档里、测试写在代码里，两者会漂移 ——
# 改名、删文件、加 `#[ignore]` 都不会让任何测试变红，只会让「我们验证过这条」
# 变成一句空话。这里把「属性 → 具体测试」的映射钉住：
#
#   1. 每条属性要么映射到一个真实存在、且没有被 `#[ignore]` 的测试；
#   2. 要么**显式登记豁免**并写明原因（豁免也是要 review 的）。
#
# 只做静态断言（存在性 + 未忽略），不重复跑测试 —— 全量测试由
# `scripts/verify-all.sh` 的第 5 步跑，这里管的是「那条测试还在不在」。
#
# 检查逻辑在 `apps/xtask`（Rust），这里只是入口：不需要系统 Python。
set -euo pipefail

cd "$(dirname "$0")/../.."

. "$(dirname "$0")/../lib/xtask.sh"

xtask_run check-security-tests
