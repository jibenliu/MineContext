#!/usr/bin/env bash
# 注释面向交付：源码注释里不出现开发过程叙事，且模块注释不无限膨胀。
#
# 判断标准（详见 docs/comment-style.md）：
#   保留 —— 非显然的「为什么」、契约/安全/不变量约束、外部系统怪癖；
#   删除 —— 复述代码、开发过程叙事、情绪化评价、已经过期的计划引用。
#
# 之所以能做成门禁：过程叙事有固定的词汇特征。它拦不住一切糟糕注释，
# 但能拦住最常见、也最没有信息量的那一类 —— 而且这类注释恰好最容易
# 在 review 里被忽略（它们读起来像"有内容"）。
#
# 长度规则做成**棘轮**（只减不增），而不是一刀切：
#   模块注释（`//!`）超过 10 行的文件必须列在 `scripts/comment-length-allow.txt`；
#   函数注释（`///` 直接贴着一个 `fn`）超过 8 行的必须列在
#   `scripts/function-doc-allow.txt`，**且每条都要写明理由**
#   —— 长注释不是错，没理由的长注释才是；
#   已经收敛（≤ 上限）却还留在名单里的条目会被判为陈旧并失败。
#
# 检查逻辑在 `apps/xtask`（Rust），这里只是入口：不需要系统 Python。
set -euo pipefail

cd "$(dirname "$0")/../.."

. "$(dirname "$0")/../lib/xtask.sh"

xtask_run check-comment-style
